// Copies the compiled AsgardVault ABI to the consumers that need it:
//   - packages/shared/src/abi.ts      (typed `as const` for viem/wagmi in the web app)
//   - apps/api/internal/chain/abi.json (parsed at runtime by the Go indexer)
import fs from "node:fs";
import path from "node:path";
import hre from "hardhat";

async function main() {
  const artifact = await hre.artifacts.readArtifact("AsgardVault");
  const root = path.resolve(__dirname, "../../..");

  const tsOut = path.join(root, "packages/shared/src/abi.ts");
  fs.mkdirSync(path.dirname(tsOut), { recursive: true });
  fs.writeFileSync(
    tsOut,
    `// AUTO-GENERATED by packages/contracts/scripts/export-abi.ts — do not edit.\n` +
      `export const asgardVaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );

  const goOut = path.join(root, "apps/api/internal/chain/abi.json");
  fs.mkdirSync(path.dirname(goOut), { recursive: true });
  fs.writeFileSync(goOut, JSON.stringify(artifact.abi, null, 2) + "\n");

  console.log(`ABI exported to:\n  ${tsOut}\n  ${goOut}`);
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
